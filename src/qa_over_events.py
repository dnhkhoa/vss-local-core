def answer_question_over_events(
    events_path: str,
    question: str,
    client: OllamaVisionClient,
    memory_db_path: str | None = None,
) -> str:
    return answer_question_with_evidence(
        events_path,
        question,
        client,
        memory_db_path=memory_db_path,
    )["answer"]


def answer_question_with_evidence(
    events_path: str,
    question: str,
    client: OllamaVisionClient,
    memory_db_path: str | None = None,
) -> dict:
    """Answer through a VSS-like retrieval + visual evidence flow.

    The events JSON is treated as a local debug/export artifact that can point us
    to sampled frames. The answer itself is generated by the VLM from retrieved
    evidence frames whenever possible.
    """

    events_file = Path(events_path)
    events_data = _load_events(events_file)
    current_segments = _segments_from_events(events_data)
    query_plan = _build_query_plan(question)
    retrieved_segments = _retrieve_segments(query_plan, current_segments, memory_db_path)

    root_dir = _infer_root_dir(events_file)
    if query_plan["needs_temporal"]:
        evidence = _collect_temporal_evidence(events_data, retrieved_segments, root_dir, query_plan)
        if not evidence:
            evidence = _collect_evidence_frames(retrieved_segments, root_dir, query_plan)
    else:
        evidence = _collect_evidence_frames(retrieved_segments, root_dir, query_plan)
    if evidence:
        answer = _answer_with_vlm(question, retrieved_segments, evidence, client)
        evidence_payload = _build_evidence_payload(root_dir, evidence)
        if answer:
            result = {
                "answer": _append_evidence_times(answer, evidence_payload),
                "evidence": evidence_payload,
                "retrieval": _build_retrieval_trace(query_plan, retrieved_segments, evidence),
            }
            _write_retrieval_report(root_dir, question, result)
            _log_training_candidate(root_dir, question, result, "vlm_answer")
            return result
        result = {
            "answer": _append_evidence_times(_not_enough_visual_evidence_answer(), evidence_payload),
            "evidence": evidence_payload,
            "retrieval": _build_retrieval_trace(query_plan, retrieved_segments, evidence),
        }
        _write_retrieval_report(root_dir, question, result)
        _log_training_candidate(root_dir, question, result, "not_enough_evidence")
        return result

    if current_segments:
        result = {
            "answer": _not_enough_visual_evidence_answer(),
            "evidence": [],
            "retrieval": _build_retrieval_trace(query_plan, retrieved_segments, evidence),
        }
        _write_retrieval_report(root_dir, question, result)
        _log_training_candidate(root_dir, question, result, "no_evidence")
        return result
    if memory_db_path:
        result = {
            "answer": (
                "Chưa có khoảnh khắc kiểm chứng phù hợp để trả lời. "
                "Hãy nạp video trước, sau đó hỏi lại."
            ),
            "evidence": [],
        }
        _log_training_candidate(root_dir, question, result, "no_evidence")
        return result
    result = {
        "answer": "Chưa có dữ liệu video để trả lời. Hãy nạp video trước.",
        "evidence": [],
    }
    _log_training_candidate(root_dir, question, result, "no_video_data")
    return result


def _load_events(events_file: Path) -> dict | None:
    try:
        data = json.loads(events_file.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return None
    return data if isinstance(data, dict) else None


def _log_training_candidate(root_dir: Path, question: str, result: dict, route: str) -> None:
    log_dir = root_dir / "outputs" / "training"
    log_dir.mkdir(parents=True, exist_ok=True)
    record = {
        "created_at": datetime.now(timezone.utc).isoformat(),
        "route": route,
        "question": question,
        "model_answer": result.get("answer"),
        "evidence": result.get("evidence") or [],
        "expected_answer": "",
        "review_status": "unreviewed",
    }
    with (log_dir / "qa_candidates.jsonl").open("a", encoding="utf-8") as file:
        file.write(json.dumps(record, ensure_ascii=False) + "\n")


def _write_retrieval_report(root_dir: Path, question: str, result: dict) -> None:
    report_dir = root_dir / "outputs"
    report_dir.mkdir(parents=True, exist_ok=True)
    report = {
        "created_at": datetime.now(timezone.utc).isoformat(),
        "question": question,
        "answer": result.get("answer"),
        "retrieval": result.get("retrieval") or {},
        "evidence": result.get("evidence") or [],
    }
    try:
        (report_dir / "retrieval_report.json").write_text(
            json.dumps(report, ensure_ascii=False, indent=2),
            encoding="utf-8",
        )
    except OSError:
        return


def _build_retrieval_trace(query_plan: dict, segments: list[dict], evidence: list[dict]) -> dict:
    return {
        "intent": {
            "asks_count": query_plan.get("asks_count"),
            "asks_color": query_plan.get("asks_color"),
            "asks_person": query_plan.get("asks_person"),
            "asks_text": query_plan.get("asks_text"),
            "asks_safety": query_plan.get("asks_safety"),
            "needs_temporal": query_plan.get("needs_temporal"),
            "target_objects": sorted(query_plan.get("target_objects") or []),
            "tokens": sorted(query_plan.get("tokens") or []),
        },
        "segments": [
            {
                "segment_id": segment.get("segment_id"),
                "time": f"{segment.get('start_time')}-{segment.get('end_time')}",
                "score": segment.get("_retrieval_score"),
                "reasons": segment.get("_retrieval_reasons") or [],
                "summary": segment.get("summary"),
                "person_count": segment.get("person_count"),
                "risk_level": segment.get("risk_level"),
            }
            for segment in segments[:MAX_RETRIEVED_SEGMENTS]
        ],
        "evidence": [
            {
                "segment_id": item.get("segment_id"),
                "timestamp": item.get("timestamp"),
                "path": item.get("path"),
                "score": item.get("retrieval_score"),
                "reasons": item.get("retrieval_reasons") or [],
                "focus": item.get("focus"),
                "type": item.get("evidence_type") or "representative_frame",
                "motion_score": item.get("motion_score"),
                "motion_label": item.get("motion_label"),
            }
            for item in evidence
        ],
    }


def _segments_from_events(events_data: dict | None) -> list[dict]:
    if not isinstance(events_data, dict):
        return []
    segments = events_data.get("segments") or []
    return [segment for segment in segments if isinstance(segment, dict)]


def _build_query_plan(question: str) -> dict:
    normalized = _normalize_text(question)
    raw_tokens = _raw_question_tokens(normalized)
    tokens = _question_tokens(normalized)
    compact = normalized.replace(" ", "")
    target_objects = _target_objects(normalized, raw_tokens, tokens)
    return {
        "question": question,
        "normalized": normalized,
        "raw_tokens": raw_tokens,
        "tokens": tokens,
        "target_objects": target_objects,
        "asks_count": any(term in normalized for term in ("bao nhieu", "so luong", "dem ", "how many", "count")),
        "asks_color": any(term in normalized for term in ("mau", "color", "mac ao", "ao mau")),
        "asks_person": any(term in tokens for term in ("nguoi", "person", "people", "worker", "staff", "human")),
        "asks_text": any(term in normalized for term in ("chu", "bien", "text", "sign", "doc duoc")),
        "asks_safety": any(term in tokens for term in ("nguyhiem", "unsafe", "danger", "risk", "fight", "violence", "fall")),
        "needs_temporal": _is_temporal_question(question),
        "is_visual": True,
        "compact": compact,
    }


def _target_objects(normalized_question: str, raw_tokens: set[str], tokens: set[str]) -> set[str]:
    if "laptop" in raw_tokens or "notebook" in raw_tokens:
        return {"laptop", "notebook"}
    if "maytinh" in raw_tokens or "computer" in raw_tokens:
        return {"computer", "laptop", "notebook", "monitor"}
    known = {
        "fan": {"quat", "fan", "ventilator"},
        "laptop": {"laptop", "computer", "notebook", "maytinh"},
        "chair": {"ghe", "chair"},
        "desk": {"ban", "desk", "table"},
        "door": {"cua", "door", "entrance"},
        "helmet": {"mu", "helmet"},
        "person": {"nguoi", "person", "people", "worker", "staff"},
    }
    targets = set()
    for canonical, aliases in known.items():
        if tokens.intersection(aliases) or any(alias in normalized_question for alias in aliases):
            targets.add(canonical)
            targets.update(aliases)
    return targets


def _retrieve_segments(
    query_plan: dict,
    current_segments: list[dict],
    memory_db_path: str | None,
) -> list[dict]:
    local_ranked = _rank_segments(current_segments, query_plan)
    memory_ranked = _search_indexed_memory(memory_db_path, query_plan)

    candidates = []
    candidates.extend(local_ranked)
    candidates.extend(memory_ranked)
    candidates.extend(_broad_visual_coverage(current_segments, query_plan))
    return _dedupe_segments(candidates)[:MAX_RETRIEVED_SEGMENTS]


def _answer_with_vlm(
    question: str,
    segments: list[dict],
    evidence: list[dict],
    client: OllamaVisionClient,
) -> str | None:
    structured_answer = _structured_count_answer_from_evidence(question, evidence)
    if structured_answer:
        return structured_answer

    if len(evidence) > VLM_IMAGE_BATCH_SIZE:
        return _answer_with_vlm_chunks(question, segments, evidence, client)

    prompt = _build_vss_qa_prompt(question, segments, evidence)
    response_text = client.analyze_images([item["path"] for item in evidence], prompt)
    parsed = _parse_json_object(response_text)
    if not isinstance(parsed, dict):
        parsed = _retry_plain_visual_answer(question, evidence, client)
    if not isinstance(parsed, dict):
        raw_answer = _clean_user_facing_text(_extract_text_answer(response_text))
        if raw_answer:
            return raw_answer
        return None

    answer = _clean_user_facing_text(str(parsed.get("answer") or "").strip())
    if not answer:
        return None

    confidence = str(parsed.get("confidence") or "unclear").strip()
    evidence_items = parsed.get("evidence")
    limits = _clean_user_facing_text(str(parsed.get("limits") or "").strip())
    if _has_temporal_evidence(evidence):
        answer = _clean_user_facing_text(_replace_static_wording(answer))
        limits = _clean_user_facing_text(_replace_static_wording(limits))

    parts = [answer]
    if isinstance(evidence_items, list) and evidence_items:
        evidence_text = "; ".join(_clean_user_facing_text(str(item)) for item in evidence_items[:4])
        parts.append("Dựa trên: " + evidence_text)
    if limits:
        parts.append("Lưu ý: " + limits)
    return "\n\n".join(parts)


def _answer_with_vlm_chunks(
    question: str,
    segments: list[dict],
    evidence: list[dict],
    client: OllamaVisionClient,
) -> str | None:
    chunk_results = []
    for index in range(0, len(evidence), VLM_IMAGE_BATCH_SIZE):
        chunk = evidence[index : index + VLM_IMAGE_BATCH_SIZE]
        prompt = _build_chunk_qa_prompt(question, chunk)
        response_text = client.analyze_images([item["path"] for item in chunk], prompt)
        parsed = _parse_json_object(response_text)
        if not isinstance(parsed, dict):
            raw_answer = _clean_user_facing_text(_extract_text_answer(response_text))
            if raw_answer:
                parsed = {"answer": raw_answer, "confidence": "unclear", "evidence": []}
        if not isinstance(parsed, dict):
            continue
        answer = _clean_user_facing_text(str(parsed.get("answer") or "").strip())
        if not answer:
            continue
        chunk_results.append(
            {
                "answer": answer,
                "confidence": str(parsed.get("confidence") or "unclear"),
                "evidence": parsed.get("evidence") or [],
                "times": [item.get("timestamp") for item in chunk if item.get("timestamp")],
                "focus": [item.get("focus") for item in chunk if item.get("focus")],
                "indexed_person_counts": [_indexed_person_count(item) for item in chunk],
            }
        )

    if not chunk_results:
        return None

    combined_answer = _summarize_chunk_answers(question, chunk_results, client)
    return _clean_user_facing_text(combined_answer)


def _summarize_chunk_answers(question: str, chunk_results: list[dict], client: OllamaVisionClient) -> str:
    count_answer = _aggregate_count_answer(question, chunk_results)
    if count_answer:
        return count_answer

    prompt = f"""/no_think
Bạn là trợ lý hỏi đáp video. Dưới đây là nhận xét từ nhiều khoảnh khắc đã kiểm tra trong video.
Hãy tổng hợp thành một câu trả lời ngắn gọn, dễ hiểu bằng tiếng Việt.
Không nhắc tới JSON, frame, batch, model hay metadata.

Câu hỏi:
{question}

Nhận xét theo từng nhóm khoảnh khắc:
{json.dumps(chunk_results, ensure_ascii=False)}

Trả về JSON:
{{"answer":"câu trả lời cuối cùng"}}"""
    response_text = client.generate_text(prompt)
    parsed = _parse_json_object(response_text)
    if isinstance(parsed, dict) and str(parsed.get("answer") or "").strip():
        return str(parsed.get("answer")).strip()
    return "; ".join(result["answer"] for result in chunk_results[:4])


def _aggregate_count_answer(question: str, chunk_results: list[dict]) -> str | None:
    plan = _build_query_plan(question)
    if not plan.get("asks_count"):
        return None
    if not plan.get("asks_person"):
        return None

    counts = []
    for result in chunk_results:
        for value in result.get("indexed_person_counts") or []:
            if isinstance(value, int) and value > 0:
                counts.append(value)
    if not counts:
        for result in chunk_results:
            for match in re.findall(r"\b(\d+)\b", str(result.get("answer") or "")):
                value = int(match)
                if 0 < value < 100:
                    counts.append(value)
    if not counts:
        return None

    max_count = max(counts)
    return f"Trong các khoảnh khắc đã kiểm tra, thấy tối đa khoảng {max_count} người."


def _structured_count_answer_from_evidence(question: str, evidence: list[dict]) -> str | None:
    plan = _build_query_plan(question)
    if not (plan.get("asks_count") and plan.get("asks_person")):
        return None
    counts = []
    for item in evidence:
        count = _indexed_person_count(item)
        if isinstance(count, int) and count > 0:
            counts.append(count)
    if not counts:
        return None
    return f"Trong các khoảnh khắc đã kiểm tra, thấy tối đa khoảng {max(counts)} người."


def _indexed_person_count(evidence_item: dict) -> int | None:
    for reason in evidence_item.get("retrieval_reasons") or []:
        match = re.match(r"people:(\d+)$", str(reason))
        if match:
            return int(match.group(1))
    return None


def _combined_confidence(chunk_results: list[dict]) -> str:
    scores = {"low": 1, "medium": 2, "high": 3}
    values = [scores.get(str(item.get("confidence") or "").lower(), 1) for item in chunk_results]
    if not values:
        return "unclear"
    average = sum(values) / len(values)
    if average >= 2.5:
        return "high"
    if average >= 1.6:
        return "medium"
    return "low"


