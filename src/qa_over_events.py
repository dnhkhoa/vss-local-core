def _segment_start_sec(segment: dict) -> float:
    for frame in segment.get("sampled_frames") or []:
        timestamp_sec = frame.get("timestamp_sec")
        if isinstance(timestamp_sec, (int, float)):
            return max(0.0, float(timestamp_sec) - 1.0)
    return _parse_time_to_seconds(str(segment.get("start_time") or "0"))


def _segment_end_sec(segment: dict, duration_seconds: float) -> float:
    parsed = _parse_time_to_seconds(str(segment.get("end_time") or "0"))
    if parsed <= 0:
        parsed = _segment_start_sec(segment) + 2.0
    return min(duration_seconds, max(parsed, _segment_start_sec(segment) + 0.25))


def _parse_time_to_seconds(value: str) -> float:
    parts = value.strip().split(":")
    try:
        if len(parts) == 3:
            hours, minutes, seconds = parts
            return int(hours) * 3600 + int(minutes) * 60 + float(seconds)
        if len(parts) == 2:
            minutes, seconds = parts
            return int(minutes) * 60 + float(seconds)
        return float(value)
    except ValueError:
        return 0.0


def _temporal_sample_times(start_sec: float, end_sec: float, count: int) -> list[float]:
    if count <= 1 or end_sec <= start_sec:
        return [start_sec]
    duration = max(0.2, end_sec - start_sec)
    return [start_sec + duration * index / (count - 1) for index in range(count)]


def _motion_score(frames: list) -> float:
    if len(frames) < 2:
        return 0.0
    scores = []
    previous = None
    for frame in frames:
        gray = cv2.cvtColor(frame, cv2.COLOR_BGR2GRAY)
        gray = cv2.resize(gray, (160, 90))
        if previous is not None:
            diff = cv2.absdiff(previous, gray)
            scores.append(float(diff.mean()))
        previous = gray
    if not scores:
        return 0.0
    return round(sum(scores) / len(scores), 3)


def _motion_label(score: float) -> str:
    if score >= 12:
        return "high"
    if score >= 4:
        return "medium"
    if score > 0:
        return "low"
    return "unknown"


def _format_time(seconds: float) -> str:
    total_seconds = int(round(seconds))
    hours = total_seconds // 3600
    minutes = (total_seconds % 3600) // 60
    secs = total_seconds % 60
    return f"{hours:02d}:{minutes:02d}:{secs:02d}"


